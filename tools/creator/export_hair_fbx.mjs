import fs from 'fs';
globalThis.document = { createElementNS: () => ({ style: {}, addEventListener(){}, removeEventListener(){}, set src(v){} }), createElement: () => ({ style: {}, getContext: () => null, addEventListener(){}, removeEventListener(){}, set src(v){} }) };
globalThis.self = globalThis;
const { FBXLoader } = await import('three/examples/jsm/loaders/FBXLoader.js');
const buf = fs.readFileSync('/mnt/user-data/uploads/Desktop/DummyHair.fbx');
const o = new FBXLoader().parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), '');
let dummy, hair; o.traverse(n => { if (n.isMesh) { if (n.name === 'Dummy') dummy = n; if (n.name === 'Hair') hair = n; } });
console.log('pos', dummy.position.toArray(), hair.position.toArray(), dummy.quaternion.toArray(), hair.quaternion.toArray());
const dp = dummy.geometry.attributes.position.array;
let top = -9; for (let i = 1; i < dp.length; i += 3) top = Math.max(top, dp[i]);
const m = (lo, hi) => { let hw = 0, zf = -9, zb = 9; for (let i = 0; i < dp.length; i += 3) { const y = dp[i + 1]; if (y < top - hi || y > top - lo) continue; hw = Math.max(hw, Math.abs(dp[i])); zf = Math.max(zf, dp[i + 2]); zb = Math.min(zb, dp[i + 2]); } return { hw, zf, zb }; };
const meas = { top, band: m(0.06, 0.10) };
console.log(meas);
const g = hair.geometry, idx = g.index ? g.index.array : null;
const P = g.attributes.position.array, N = g.attributes.normal.array, U = g.attributes.uv.array;
const vc = P.length / 3;
const nIdx = idx ? idx.length : vc;
const bin = Buffer.concat([Buffer.from(new Float32Array(P).buffer), Buffer.from(new Float32Array(N).buffer), Buffer.from(new Float32Array(U).buffer), Buffer.from(new Uint32Array(idx || Array.from({ length: vc }, (_, i) => i)).buffer)]);
fs.writeFileSync('/home/claude/tv/public/creator/assets/hair1.bin', bin);
fs.writeFileSync('/home/claude/tv/public/creator/assets/hair1.json', JSON.stringify({ verts: vc, idx: nIdx, dummy: meas }));
console.log(vc, nIdx, bin.length);
